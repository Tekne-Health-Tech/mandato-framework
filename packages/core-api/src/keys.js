// Per-request key ring (design 0001 §4.6, 0002 §8). Wrapped keys are read in the request's transaction and unwrapped
// with the KEK the envelope names; the database never sees an unwrapped key. Keys are reloaded on every transaction,
// so a key that stopped being active is never used to encrypt.
import { randomBytes } from 'node:crypto';
import * as c from '../../crypto/src/envelope.js';

const BI_EMAIL = 'bi:email:v1';

async function slugOf(tx) {
  const { rows } = await tx.query('select slug from core.instance');
  if (rows.length !== 1) throw new Error('keys: instance row missing');
  return rows[0].slug;
}
const unwrap = (env, slug, k) => c.unwrapDek(c.loadKek(c.keyIdOf(k.enc_wrapped_key), env), k.enc_wrapped_key, slug, k.purpose, k.key_id);

/** Keys of the staff columns and the e-mail index (core.staff_keys: aal2 callers). */
export async function staffKeyring(tx, env) {
  const slug = await slugOf(tx);
  const { rows } = await tx.query('select key_id, purpose, version, state, enc_wrapped_key from core.staff_keys()');
  const active = new Map(); const byId = new Map();
  for (const k of rows) {
    const dek = unwrap(env, slug, k);
    byId.set(k.key_id, dek);
    if (k.state === 'active') active.set(k.purpose, { keyId: k.key_id, dek, version: k.version });
  }
  return {
    encrypt(column, rowId, text) {
      const k = active.get(column);
      if (!k) throw new Error(`keys: no active key for ${column}`);
      return c.seal(k.dek, k.keyId, Buffer.from(text, 'utf8'), c.dataAad(slug, column, rowId));
    },
    decrypt(column, rowId, envelope) {
      const dek = byId.get(c.keyIdOf(envelope));
      if (!dek) throw new Error('keys: unknown key');
      return c.open(dek, envelope, c.dataAad(slug, column, rowId)).toString('utf8');
    },
    emailIndex(email) { return indexWith(active.get(BI_EMAIL), email); },
  };
}

/** The e-mail index key only (core.index_key: any api_rt caller, used by the sign-up hook). */
export async function emailIndexer(tx, env) {
  const slug = await slugOf(tx);
  const { rows } = await tx.query("select key_id, version, enc_wrapped_key from core.index_key('bi:email:v1')");
  if (rows.length !== 1) throw new Error('keys: no active e-mail index key');
  const k = rows[0];
  const dek = unwrap(env, slug, { ...k, purpose: BI_EMAIL });
  return (email) => indexWith({ dek, version: k.version }, email);
}

function indexWith(k, email) {
  if (!k) throw new Error('keys: no active e-mail index key');
  return c.emailIndex(k.dek, k.version, email);
}

/** UUIDv7 (0001 §4.2: ids are generated by the application so ciphertext can bind them). */
export function uuid7(ms = Date.now()) {
  const b = randomBytes(16);
  b.writeUIntBE(ms, 0, 6);
  b[6] = (b[6] & 0x0f) | 0x70;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = b.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
