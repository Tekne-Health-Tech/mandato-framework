#!/usr/bin/env bash
# Prints the role × table × verb grant matrix of the test database as Markdown (design 0001 §4.1).
set -euo pipefail
DB=${TEST_DB:-mandato_test}
echo "# Grant matrix (generated by packages/db/test/grants.sh — do not edit)"
echo
echo "| Role | Object | Privileges |"
echo "| --- | --- | --- |"
psql -X -At -U postgres -d "$DB" -F '|' -c "
with roles(r) as (values ('api_rt'),('worker_c1'),('worker_c2'),('worker_c3'),('migrator'),('scheduler'),('fetch_c1'),('anon'),('authenticated')),
t as (
  select grantee r, table_schema||'.'||table_name obj, string_agg(privilege_type, ', ' order by privilege_type) p
    from information_schema.role_table_grants
   where grantee in (select r from roles) and table_schema in ('core','audit','api')
   group by 1,2),
c as (
  select grantee r, table_schema||'.'||table_name||' ('||column_name||')' obj, string_agg(privilege_type, ', ' order by privilege_type) p
    from information_schema.column_privileges cp
   where grantee in (select r from roles) and table_schema in ('core','audit','api')
     and not exists (select 1 from information_schema.role_table_grants g
                      where g.grantee=cp.grantee and g.table_schema=cp.table_schema and g.table_name=cp.table_name and g.privilege_type=cp.privilege_type)
   group by 1,2),
f as (
  select r.r, n.nspname||'.'||p.proname||'('||pg_get_function_identity_arguments(p.oid)||')' obj, 'EXECUTE' p
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace cross join roles r
   where n.nspname in ('core','audit','api') and has_function_privilege(r.r, p.oid, 'EXECUTE'))
select r, obj, p from (select * from t union all select * from c union all select * from f) x order by 1,2" |
  awk -F'|' '{ printf "| %s | %s | %s |\n", $1, $2, $3 }'
